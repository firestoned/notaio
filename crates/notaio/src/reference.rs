/// One row per field: `(path, type, required, description)`.
type FieldRow = (String, String, bool, String);

fn type_of(node: &Value) -> String {
    let base = node.get("type").and_then(Value::as_str).unwrap_or("object");
    if let Some(values) = node.get("enum").and_then(Value::as_array) {
        let v: Vec<String> = values
            .iter()
            .filter_map(Value::as_str)
            .map(|s| format!("`{s}`"))
            .collect();
        return format!("{base}: {}", v.join(", "));
    }
    match base {
        "array" => format!(
            "array of {}",
            node.get("items").map_or("object".to_string(), type_of)
        ),
        "object" if node.get("additionalProperties").is_some() => format!(
            "map of {}",
            node.get("additionalProperties")
                .map_or("object".to_string(), type_of)
        ),
        _ => base.to_string(),
    }
}

fn walk(node: &Value, path: &str, required: bool, rows: &mut Vec<FieldRow>) {
    let description = node
        .get("description")
        .and_then(Value::as_str)
        .unwrap_or_default();
    if !path.is_empty() {
        rows.push((path.to_string(), type_of(node), required, cell(description)));
    }
    let child = match node.get("type").and_then(Value::as_str) {
        Some("array") => node.get("items").map(|i| (i, format!("{path}[]"))),
        _ => None,
    };
    if let Some((items, p)) = child {
        walk_properties(items, &p, rows);
        return;
    }
    walk_properties(node, path, rows);
}

fn walk_properties(node: &Value, path: &str, rows: &mut Vec<FieldRow>) {
    let Some(props) = node.get("properties").and_then(Value::as_object) else {
        return;
    };
    let required: BTreeSet<&str> = node
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    for (name, child) in props {
        let p = if path.is_empty() {
            name.clone()
        } else {
            format!("{path}.{name}")
        };
        walk(child, &p, required.contains(name.as_str()), rows);
    }
}

fn crd_section(crd: &Value) -> String {
    let kind = crd["spec"]["names"]["kind"].as_str().unwrap_or_default();
    let scope = crd["spec"]["scope"].as_str().unwrap_or_default();
    let short: Vec<&str> = crd["spec"]["names"]["shortNames"]
        .as_array()
        .map(|a| a.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let version = &crd["spec"]["versions"][0];
    let schema = &version["schema"]["openAPIV3Schema"];
    let mut out = String::new();
    let scope = if scope == "Namespaced" {
        "namespaced"
    } else {
        "cluster scoped"
    };
    let _ = writeln!(
        out,
        "## {kind}\n\n`{}/{}`, {scope}, short name `{}`.\n",
        crd["spec"]["group"].as_str().unwrap_or_default(),
        version["name"].as_str().unwrap_or_default(),
        short.join("`, `"),
    );
    // The spec struct's doc comment; the root's description is kube-derive's boilerplate.
    if let Some(d) = schema["properties"]["spec"]
        .get("description")
        .and_then(Value::as_str)
    {
        let _ = writeln!(out, "{}\n", cell(d));
    }
    for part in ["spec", "status"] {
        let Some(node) = schema["properties"].get(part) else {
            continue;
        };
        let mut rows = Vec::new();
        walk_properties(node, "", &mut rows);
        if rows.is_empty() {
            continue;
        }
        let _ = writeln!(
            out,
            "### `{part}`\n\n| Field | Type | Required | Description |\n| --- | --- | --- | --- |"
        );
        for (path, ty, req, desc) in rows {
            let _ = writeln!(
                out,
                "| `{path}` | {ty} | {} | {desc} |",
                if req { "yes" } else { "" }
            );
        }
        out.push('\n');
    }
    out
}

