/// `(name as served, type, help, label names)` for every metric `/metrics` serves.
fn metric_rows() -> Vec<(String, String, String, BTreeSet<String>)> {
    let (policies, grants) = sample_snapshot().unwrap_or_default();
    let now = Utc
        .with_ymd_and_hms(2026, 1, 1, 0, 30, 0)
        .single()
        .unwrap_or_default();
    let text = metrics::render(
        &Counters::default(),
        &Snapshot {
            policies: &policies,
            profiles: &[],
            grants: &grants,
            now,
            bundle_lifetime: Duration::hours(1),
        },
    );
    let mut rows: BTreeMap<String, (String, String, BTreeSet<String>)> = BTreeMap::new();
    let mut order = Vec::new();
    for line in text.lines() {
        if let Some(rest) = line.strip_prefix("# TYPE ") {
            if let Some((name, ty)) = rest.split_once(' ') {
                order.push(name.to_string());
                rows.entry(name.to_string()).or_default().0 = ty.to_string();
            }
        } else if let Some(rest) = line.strip_prefix("# HELP ") {
            if let Some((name, help)) = rest.split_once(' ') {
                rows.entry(name.to_string()).or_default().1 = help.to_string();
            }
        } else if !line.starts_with('#') {
            let (series, labels) = match line.split_once('{') {
                Some((s, rest)) => (s, rest.split_once('}').map_or("", |(l, _)| l)),
                None => (line.split(' ').next().unwrap_or_default(), ""),
            };
            let family = series.strip_suffix("_total").unwrap_or(series);
            if let Some(r) = rows.get_mut(family) {
                for pair in labels.split(',').filter(|p| !p.is_empty()) {
                    if let Some((k, _)) = pair.split_once('=') {
                        r.2.insert(k.to_string());
                    }
                }
            }
        }
    }
    order
        .into_iter()
        .filter_map(|name| {
            let (ty, help, labels) = rows.remove(&name)?;
            let served = if ty == "counter" {
                format!("{name}_total")
            } else {
                name
            };
            Some((served, ty, help, labels))
        })
        .collect()
}

